const fs = require('fs');
const assert = require('node:assert/strict');
const XLSX = require('xlsx');
const ts = require('typescript');
function load(file, extra={}) {
  const module={exports:{}};
  const code=ts.transpileModule(fs.readFileSync(file,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020,experimentalDecorators:true}}).outputText;
  new Function('require','module','exports',code)(name=>extra[name]||(name==='xlsx'?XLSX:name==='@angular/core'?{Injectable:()=>x=>x}:{}),module,module.exports);
  return module.exports;
}
const {MonthlyReportService}=load('src/app/services/monthly-report.service.ts');
const service=new MonthlyReportService();
const services=JSON.parse(fs.readFileSync('src/assets/data/servicos.json','utf8'));
const buffer=fs.readFileSync(process.argv[2]);
const report=service.parse(buffer.buffer.slice(buffer.byteOffset,buffer.byteOffset+buffer.byteLength),'Medição mensal.xlsx',services);
assert.equal(report.records.length,5944);
assert.equal(report.ignoredGroups,333);
assert.equal(report.rejected.length,0);
assert.equal(report.records.filter(r=>r.status==='Cancelada').length,93);
assert.equal(report.records.filter(r=>r.warnings.some(w=>w.startsWith('Voo/rota'))).length,3);
const example=report.records.find(r=>r.os==='1919696');
assert.ok(example);
assert.equal(example.posto,'Inspeção em Aeronave 1');
const toRow=(record,offset=-180)=>{
  const reference=record.primaryStart-offset;
  const date=XLSX.SSF.format('yyyy-mm-dd',reference/1440), time=XLSX.SSF.format('hh:mm',reference/1440);
  return {'TÍTULO':[record.base,record.voo,record.destino,record.atendimento].join('_'),'UNIDADE DE GESTÃO':record.unidade,_baseAtend:record.base,_baseDest:record.destino,_classif:record.atendimento,_dataISO:date,_horaISO:time,[record.posto]:offset,['_contratual_'+record.posto]:record.primaryEnd-record.primaryStart};
};
const row=toRow(example);
assert.ok(service.match(report,row,example.posto).some(m=>m.record.os===example.os&&m.level==='programacao'));
assert.equal(service.match(report,{...row,'TÍTULO':row['TÍTULO'].replace('_1653_','_9999_')},example.posto).length,0);
assert.equal(service.match(report,{...row,_dataISO:'2027-03-01'},example.posto).length,0);
assert.equal(service.match(report,{...row,'UNIDADE DE GESTÃO':'Outra Empresa'},example.posto).length,0);
assert.equal(service.match(report,row,'GRIS').length,0);
const cancelled=report.records.find(r=>r.status==='Cancelada'&&services.some(s=>s.label===r.posto));
assert.ok(service.match(report,toRow(cancelled),cancelled.posto).some(m=>m.record.os===cancelled.os&&m.level==='cancelada'));
const inconsistent=report.records.find(r=>r.warnings.some(w=>w.startsWith('Voo/rota')));
assert.ok(service.match(report,toRow(inconsistent),inconsistent.posto).some(m=>m.record.os===inconsistent.os));
const overnight=report.records.find(r=>Math.floor(r.primaryStart/1440)!==Math.floor(r.primaryEnd/1440)&&services.some(s=>s.label===r.posto));
assert.ok(service.match(report,toRow(overnight),overnight.posto).some(m=>m.record.os===overnight.os&&m.level==='programacao'));
const alternate=report.records.find(r=>r.primaryStart-r.alternateStart>60&&services.some(s=>s.label===r.posto));
const alternateRow=toRow({...alternate,primaryStart:alternate.alternateStart,primaryEnd:alternate.alternateEnd});
assert.ok(service.match(report,alternateRow,alternate.posto).some(m=>m.record.os===alternate.os&&m.level==='possivel'));
